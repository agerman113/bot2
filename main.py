# ==================== ОСНОВНОЙ КОД ====================
def main():
    if not GROUP_TOKEN or not GROUP_ID:
        logger.error("Не установлены переменные окружения!")
        return

    try:
        vk_session = vk_api.VkApi(token=GROUP_TOKEN)
        vk = vk_session.get_api()
        longpoll = VkBotLongPoll(vk_session, GROUP_ID)

        logger.info(f"Бот запущен! ID группы: {GROUP_ID}")

        for event in longpoll.listen():
            if event.type == VkBotEventType.MESSAGE_NEW:
                message = event.obj.message
                user_id = message['from_id']
                text = message['text'].lower() if 'text' in message else ''

                # Инициализация пользователя
                if user_id not in user_progress:
                    user_progress[user_id] = {
                        'current_bundle': None,
                        'current_step': 0,
                        'completed_bundles': [],
                        'registration_time': datetime.now()
                    }

                # УНИФИЦИРОВАННЫЙ ВХОД В ГЛАВНОЕ МЕНЮ
                if (text in ['начать', 'старт', 'start', 'меню', 'привет', 'назад', 'главное меню', 'главное', 'домой', 'home', 'main'] or
                    '🔙 в главное меню' in text or
                    'в главное меню' in text):

                    vk.messages.send(
                        user_id=user_id,
                        message=get_welcome_message(),
                        keyboard=get_main_keyboard(),
                        random_id=0,
                        dont_parse_links=1
                    )
                    continue

                # Кнопка "Начать зарабатывать"
                elif 'начать зарабатывать' in text:
                    response = (
                        "🎯 *ВЫБЕРИ СВОЙ ПУТЬ К ПЕРВОМУ ЗАРАБОТКУ:*\n\n"
                        "У нас есть *15 готовых связок* разной сложности:\n\n"
                        "★☆☆ *Для новичков:*\n"
                        "• 👨‍🏫 S-репетиторы-F (15-20 мин, 500-2000 руб)\n"
                        "• 🎓 S-дипломы-VS (20-30 мин, 800-3000 руб)\n\n"
                        "★★☆ *Для опытных:*\n"
                        "• 🎯 S-K-таргетологи-K (25-35 мин, 1000-5000 руб)\n"
                        "• 🤖 S-таргетологи-A (25-35 мин, 1000-5000 руб)\n"
                        "• 📢 AYF-таргетологи-S (25-35 мин, 1500-6000 руб)\n"
                        "• 🚰 S-сантехники-YA (25-35 мин, 1000-4000 руб)\n\n"
                        "★★★ *Для профессионалов:*\n"
                        "• 🏢 K-B2B-A (30-40 мин, 2000-8000 руб)\n"
                        "• ⚖️ Consenta-K-A-E (40-50 мин, 2000-10000 руб)\n\n"
                        "★★★★ *Экспертный уровень:*\n"
                        "• 🏗️ G-Consenta-K-A-E (50-60 мин, 3000-20000 руб)\n\n"
                        "🚀 *AI-ОПТИМИЗИРОВАННЫЕ СВЯЗКИ:*\n"
                        "• 🖥️ AI*: VPS для ботов + сервис упоминаний\n"
                        "• 🔍 AI*: VPS для ботов + перехватчик заявок\n"
                        "• 📬 AI*: Email рассылки + перехватчик заявок\n"
                        "• 🎯 AI*: Партнерские оферы + сервис упоминаний\n"
                        "• 📧 AI*: Партнерские оферы + email рассылки\n"
                        "• 💻 AI*: VPS для ботов + биржа фриланса\n\n"
                        "*Какую связку выбираешь?*"
                    )

                    vk.messages.send(
                        user_id=user_id,
                        message=response,
                        keyboard=get_bundles_keyboard(),
                        random_id=0
                    )

                # Все связки (страница 1)
                elif 'все связки' in text or '15 шт' in text:
                    vk.messages.send(
                        user_id=user_id,
                        message="🎯 *ОСНОВНЫЕ СВЯЗКИ (1-8):*\nНажми '🔽 Еще связки' чтобы увидеть остальные связки",
                        keyboard=get_bundles_keyboard(),
                        random_id=0
                    )

                # Вторая страница связок
                elif 'еще связки' in text:
                    vk.messages.send(
                        user_id=user_id,
                        message="🚀 *ОСТАЛЬНЫЕ СВЯЗКИ (9-15):*\nВключая AI-оптимизированные связки для максимальной эффективности!",
                        keyboard=get_bundles_keyboard_page2(),
                        random_id=0
                    )

                # Назад к основным связкам
                elif 'основные связки' in text:
                    vk.messages.send(
                        user_id=user_id,
                        message="🎯 *ОСНОВНЫЕ СВЯЗКИ (1-8):*",
                        keyboard=get_bundles_keyboard(),
                        random_id=0
                    )

                # Инфо о проекте
                elif 'инфо' in text or 'о проекте' in text:
                    vk.messages.send(
                        user_id=user_id,
                        message=INFO_MESSAGE,
                        keyboard=get_back_keyboard(),
                        random_id=0,
                        dont_parse_links=1
                    )

                # К выбору связки
                elif 'к выбору связки' in text or '🔙 к выбору связки' in text:
                    user_progress[user_id]['current_bundle'] = None
                    user_progress[user_id]['current_step'] = 0

                    vk.messages.send(
                        user_id=user_id,
                        message="Выбери связку для выполнения:",
                        keyboard=get_bundles_keyboard(),
                        random_id=0
                    )

                # Обработка выбора связки
                elif any(phrase in text for phrase in [
                    's-репетиторы-f', 's-k-таргетологи-k', 's-таргетологи-a',
                    'ayf-таргетологи-s', 'k-b2b-a', 's-дипломы-vs',
                    'с-дипломы-vs', 'дипломы-vs', 's-сантехники-ya',
                    'consenta-k-a-e', 'g-consenta-k-a-e',
                    'vps+упоминания', 'vps+перехват', 'email+перехват',
                    'оферы+упоминания', 'оферы+email', 'vps+фриланс', 'ai*:'
                ]):
                    # Определяем выбранную связку
                    bundle_id = None

                    # Проверяем связку "S-дипломы-VS" в первую очередь
                    if any(phrase in text for phrase in ['s-дипломы-vs', 'с-дипломы-vs', 'дипломы-vs']):
                        bundle_id = 6
                    elif 's-репетиторы-f' in text or 'репетиторы-f' in text:
                        bundle_id = 1
                    elif 's-k-таргетологи-k' in text:
                        bundle_id = 2
                    elif 's-таргетологи-a' in text:
                        bundle_id = 3
                    elif 'ayf-таргетологи-s' in text:
                        bundle_id = 4
                    elif 'k-b2b-a' in text:
                        bundle_id = 5
                    elif 's-сантехники-ya' in text:
                        bundle_id = 7
                    elif 'consenta-k-a-e' in text and 'g-' not in text:
                        bundle_id = 8
                    elif 'g-consenta-k-a-e' in text:
                        bundle_id = 9
                    elif 'vps+упоминания' in text or 'ai*: vps для ботов + сервис упоминаний' in text:
                        bundle_id = 10
                    elif 'vps+перехват' in text or 'ai*: vps для ботов + перехватчик заявок' in text:
                        bundle_id = 11
                    elif 'email+перехват' in text or 'ai*: email рассылки + перехватчик заявок' in text:
                        bundle_id = 12
                    elif 'оферы+упоминания' in text or 'ai*: партнерские оферы + сервис упоминаний' in text:
                        bundle_id = 13
                    elif 'оферы+email' in text or 'ai*: партнерские оферы + email рассылки' in text:
                        bundle_id = 14
                    elif 'vps+фриланс' in text or 'ai*: vps для ботов + биржа фриланса' in text:
                        bundle_id = 15

                    if bundle_id and bundle_id in BUNDLES:
                        bundle = BUNDLES[bundle_id]
                        user_progress[user_id]['current_bundle'] = bundle_id
                        user_progress[user_id]['current_step'] = 1

                        # Показываем информацию о связке
                        response = (
                            f"{bundle['emoji']} *{bundle['name']}*\n"
                            f"──────────────────\n"
                            f"📊 Сложность: {bundle['difficulty']}\n"
                            f"⏱ Время: {bundle['time']}\n"
                            f"💰 Потенциал: {bundle['potential']}\n\n"
                            f"*{bundle['description']}*\n\n"
                            f"📋 *ВСЕГО ШАГОВ: {len(bundle['steps'])}*\n\n"
                            f"Готов начать? Переходим к первому шагу!"
                        )

                        # Показываем первый шаг
                        step = bundle['steps'][0]
                        has_ref_link = step.get('ref_link') is not None or step.get('ref_links') is not None

                        step_response = (
                            f"🚀 *ШАГ {step['number']}: {step['title']}*\n"
                            f"──────────────────\n"
                            f"{step['description']}\n\n"
                            f"📌 *ТВОЕ ДЕЙСТВИЕ:*\n"
                            f"{step['action']}"
                        )

                        if step.get('note'):
                            step_response += f"\n\n📝 *ПРИМЕЧАНИЕ:* {step['note']}"

                        if step.get('ref_text'):
                            step_response += f"\n\n🔗 *ССЫЛКА:* {step['ref_text']}"

                        keyboard = get_bundle_action_keyboard(
                            bundle_id, 1, len(bundle['steps']), has_ref_link
                        )

                        vk.messages.send(
                            user_id=user_id,
                            message=response,
                            random_id=0
                        )

                        vk.messages.send(
                            user_id=user_id,
                            message=step_response,
                            keyboard=keyboard,
                            random_id=0
                        )

                # ОФОРМИТЬ ИП - ИСПРАВЛЕННАЯ ПРОВЕРКА
                # Важно: эта проверка должна быть ПОСЛЕ проверки связок
                elif any(ip_text in text for ip_text in ['оформить ип', 'ип']):
                    # Дополнительная проверка: если текст содержит "дипломы-vs", это не кнопка ИП
                    if any(phrase in text for phrase in ['s-дипломы-vs', 'с-дипломы-vs', 'дипломы-vs']):
                        # Это связка S-дипломы-VS, пропускаем обработку ИП
                        pass
                    else:
                        vk.messages.send(
                            user_id=user_id,
                            message=IP_MESSAGE,
                            keyboard=get_back_keyboard(),
                            random_id=0,
                            dont_parse_links=1
                        )

                # Перейти по ссылке
                elif 'перейти по ссылке' in text:
                    bundle_id = user_progress[user_id]['current_bundle']
                    current_step = user_progress[user_id]['current_step'] - 1

                    if bundle_id and bundle_id in BUNDLES:
                        bundle = BUNDLES[bundle_id]
                        if current_step >= 0 and current_step < len(bundle['steps']):
                            step = bundle['steps'][current_step]

                            if step.get('ref_links'):
                                response = "🔗 *ДОСТУПНЫЕ ССЫЛКИ:*\n\n"
                                for link in step['ref_links']:
                                    response += f"{link['text']}:\n{link['url']}\n\n"
                            elif step.get('ref_link'):
                                response = f"🔗 *ТВОЯ ССЫЛКА:*\n{step['ref_link']}"
                            else:
                                response = "На этом шаге нет ссылки для перехода. Переходи к следующему шагу!"

                            response += "\n\n*После перехода вернись в бота!*"

                            vk.messages.send(
                                user_id=user_id,
                                message=response,
                                random_id=0,
                                dont_parse_links=1
                            )

                # Шаг выполнен
                elif 'шаг выполнен' in text:
                    bundle_id = user_progress[user_id]['current_bundle']
                    current_step = user_progress[user_id]['current_step']

                    if bundle_id and bundle_id in BUNDLES:
                        bundle = BUNDLES[bundle_id]

                        if current_step <= len(bundle['steps']):
                            response = f"✅ *Отлично! Шаг {current_step} выполнен!*\n\n"

                            if current_step < len(bundle['steps']):
                                response += "Нажми *'➡️ Следующий шаг'*, чтобы продолжить."
                            else:
                                response += "Ты выполнил все шаги! Нажми *'🎉 Завершить связку'*."

                            vk.messages.send(
                                user_id=user_id,
                                message=response,
                                random_id=0
                            )

                # Следующий шаг
                elif 'следующий шаг' in text:
                    bundle_id = user_progress[user_id]['current_bundle']
                    current_step_idx = user_progress[user_id]['current_step']

                    if bundle_id and bundle_id in BUNDLES:
                        bundle = BUNDLES[bundle_id]

                        if current_step_idx < len(bundle['steps']):
                            step = bundle['steps'][current_step_idx]
                            user_progress[user_id]['current_step'] += 1

                            has_ref_link = step.get('ref_link') is not None or step.get('ref_links') is not None

                            response = (
                                f"🚀 *ШАГ {step['number']}: {step['title']}*\n"
                                f"──────────────────\n"
                                f"{step['description']}\n\n"
                                f"📌 *ТВОЕ ДЕЙСТВИЕ:*\n"
                                f"{step['action']}"
                            )

                            if step.get('note'):
                                response += f"\n\n📝 *ПРИМЕЧАНИЕ:* {step['note']}"

                            if step.get('ref_text'):
                                response += f"\n\n🔗 *ССЫЛКА:* {step['ref_text']}"

                            keyboard = get_bundle_action_keyboard(
                                bundle_id, step['number'], len(bundle['steps']), has_ref_link
                            )

                            vk.messages.send(
                                user_id=user_id,
                                message=response,
                                keyboard=keyboard,
                                random_id=0
                            )
                        else:
                            # Все шаги выполнены
                            response = (
                                f"🎉 *ПОЗДРАВЛЯЮ!* Ты выполнил все {len(bundle['steps'])} шагов связки *{bundle['name']}*!\n\n"
                                f"💰 *ПОТЕНЦИАЛЬНЫЙ ЗАРАБОТОК:* {bundle['potential']}\n\n"
                                f"Что дальше?\n"
                                f"1. Повтори связку для закрепления\n"
                                f"2. Выбери новую связку\n"
                                f"3. Оформи ИП для увеличения дохода\n"
                                f"4. Свяжись со мной для получения кода бота\n\n"
                                f"📧 Остались вопросы? Пиши на почту: agerman113@vk.com"
                            )

                            if bundle_id not in user_progress[user_id]['completed_bundles']:
                                user_progress[user_id]['completed_bundles'].append(bundle_id)

                            vk.messages.send(
                                user_id=user_id,
                                message=response,
                                keyboard=get_main_keyboard(),
                                random_id=0
                            )

                # Все шаги связки
                elif 'все шаги связки' in text:
                    bundle_id = user_progress[user_id]['current_bundle']

                    if bundle_id and bundle_id in BUNDLES:
                        bundle = BUNDLES[bundle_id]

                        response = f"📋 *ВСЕ ШАГИ СВЯЗКИ '{bundle['name']}':*\n\n"

                        for i, step in enumerate(bundle['steps'], 1):
                            response += f"{i}. *{step['title']}*\n"
                            if step.get('note'):
                                response += f"   📝 {step['note']}\n"
                            response += "\n"

                        response += f"*Всего шагов: {len(bundle['steps'])}*\n\n"
                        response += "📧 *По всем вопросам:* agerman113@vk.com"

                        vk.messages.send(
                            user_id=user_id,
                            message=response,
                            random_id=0
                        )

                # Завершить связку
                elif 'завершить связку' in text:
                    bundle_id = user_progress[user_id]['current_bundle']

                    if bundle_id and bundle_id in BUNDLES:
                        bundle = BUNDLES[bundle_id]

                        if bundle_id not in user_progress[user_id]['completed_bundles']:
                            user_progress[user_id]['completed_bundles'].append(bundle_id)

                        completed = len(user_progress[user_id]['completed_bundles'])

                        response = (
                            f"🎉 *СВЯЗКА '{bundle['name']}' ЗАВЕРШЕНА!*\n\n"
                            f"✨ *ТВОИ ДОСТИЖЕНИЯ:*\n"
                            f"• Завершено связок: {completed}\n"
                            f"• Освоена новая ниша\n"
                            f"• Получен опыт работы с партнерками\n\n"
                            f"🚀 *РЕКОМЕНДАЦИИ НА БУДУЩЕЕ:*\n"
                            f"1. Повтори эту связку 2-3 раза\n"
                            f"2. Попробуй другую связку\n"
                            f"3. Оформи ИП для серьезного дохода\n"
                            f"4. Свяжись со мной для масштабирования\n\n"
                            f"📧 *Остались вопросы? Пиши на почту:* agerman113@vk.com\n\n"
                            f"*Выбери следующее действие:*"
                        )

                        vk.messages.send(
                            user_id=user_id,
                            message=response,
                            keyboard=get_main_keyboard(),
                            random_id=0
                        )

                        user_progress[user_id]['current_bundle'] = None
                        user_progress[user_id]['current_step'] = 0

    except Exception as e:
        logger.error(f"Ошибка в боте: {e}", exc_info=True)

if __name__ == '__main__':
    main()


